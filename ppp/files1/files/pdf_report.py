# ─────────────────────────────────────────────────

def generate_quick_summary_pdf(
    stats: dict,
    roi_info: dict = None,
    output_path: str = None,
) -> str:
    """
    Generate a short 1-2 page quick summary PDF.

    Parameters
    ----------
    stats : dict
        Summary statistics. Expected keys:
        - 'total_detections' : int
        - 'severity_counts'  : dict mapping severity -> count
        - 'avg_confidence'   : float
        - 'affected_tiles'   : int
        - 'gps_hotspots'     : int
        - 'top_class'        : str  (most frequent anomaly type)
        - 'assessment'       : str  (overall assessment text)
        - 'generated_at'     : str  (timestamp)
    roi_info : dict, optional
        Region of interest information. Defaults to config.ROI.
    output_path : str, optional
        Path for the output PDF.

    Returns
    -------
    str
        The absolute path to the generated PDF.
    """
    if roi_info is None:
        roi_info = ROI
    if output_path is None:
        output_path = str(
            Path(INFER["report_pdf"]).parent / "quick_summary.pdf"
        )

    output_path = Path(output_path)
    output_path.parent.mkdir(parents=True, exist_ok=True)

    pdf = AquaSentinelPDF(orientation="P", unit="mm", format="A4")
    pdf.alias_nb_pages()
    pdf.set_auto_page_break(auto=True, margin=20)
    pdf.add_page()

    # Title bar
    pdf.set_fill_color(*COLOR_HEADER_BG)
    pdf.set_text_color(255, 255, 255)
    pdf.set_font("Helvetica", "B", 18)
    pdf.cell(0, 14, "  AQUA-SENTINEL AI  --  QUICK SUMMARY", fill=True,
             new_x="LMARGIN", new_y="NEXT")
    pdf.ln(2)

    # Accent line
    pdf.set_draw_color(*COLOR_ACCENT_LINE)
    pdf.set_line_width(0.8)
    pdf.line(pdf.l_margin, pdf.get_y(), pdf.w - pdf.r_margin, pdf.get_y())
    pdf.ln(6)

    # Region info
    pdf.set_text_color(*COLOR_BODY_TEXT)
    pdf.set_font("Helvetica", "B", 10)
    water_body = roi_info.get("water_body", roi_info.get("name", "Unknown"))
    city = roi_info.get("city", "Unknown")
    state = roi_info.get("state", "Unknown")
    pdf.cell(0, 7, f"Region: {water_body}, {city}, {state}", new_x="LMARGIN", new_y="NEXT")
    generated_at = stats.get("generated_at", datetime.utcnow().strftime(TIMESTAMP_FMT))
    pdf.set_font("Helvetica", "", 9)
    pdf.cell(0, 7, f"Generated: {generated_at}", new_x="LMARGIN", new_y="NEXT")
    pdf.ln(6)

    # Key metrics
    _add_header(pdf, "KEY METRICS")
    pdf.ln(2)

    total = stats.get("total_detections", 0)
    avg_conf = stats.get("avg_confidence", 0)
    tiles = stats.get("affected_tiles", 0)
    gps = stats.get("gps_hotspots", 0)
    top_class = stats.get("top_class", "N/A")

    metrics = [
        ("Total Detections", str(total)),
        ("Average Confidence", f"{avg_conf:.1%}" if isinstance(avg_conf, float) else str(avg_conf)),
        ("Affected Tiles", str(tiles)),
        ("GPS-Located Hotspots", str(gps)),
        ("Most Frequent Anomaly", top_class),
    ]

    pdf.set_font("Helvetica", "", 10)
    for label, value in metrics:
        pdf.set_font("Helvetica", "B", 10)
        pdf.cell(55, 7, f"{label}:")
        pdf.set_font("Helvetica", "", 10)
        pdf.cell(0, 7, value, new_x="LMARGIN", new_y="NEXT")

    pdf.ln(4)

    # Severity breakdown
    sev_counts = stats.get("severity_counts", {})
    if sev_counts:
        _add_header(pdf, "SEVERITY BREAKDOWN")
        pdf.ln(2)
        for sev in SEVERITY_ORDER:
            count = sev_counts.get(sev, sev_counts.get(sev.lower(), 0))
            if count > 0 or True:  # Show all severities
                pdf.cell(10, 7, "")
                _add_severity_badge(pdf, sev)
                pdf.set_font("Helvetica", "", 10)
                pdf.cell(5, 6, "")
                pdf.cell(0, 6, f"{count} detection(s)", new_x="LMARGIN", new_y="NEXT")
        pdf.ln(4)

    # Assessment
    assessment = stats.get("assessment", "")
    if assessment:
        _add_header(pdf, "OVERALL ASSESSMENT")
        pdf.ln(2)
        pdf.set_font("Helvetica", "", 10)
        pdf.multi_cell(0, 7, assessment, new_x="LMARGIN", new_y="NEXT")
        pdf.ln(4)

    # Classification notice
    pdf.ln(6)
    pdf.set_font("Courier", "B", 8)
    pdf.set_text_color(180, 60, 60)
    pdf.cell(0, 6, "CONFIDENTIAL -- FOR AUTHORIZED PERSONNEL ONLY", align="C",
             new_x="LMARGIN", new_y="NEXT")
    pdf.set_text_color(*COLOR_BODY_TEXT)

    # Write PDF
    pdf.output(str(output_path))
    print(f"[PDF] Quick summary generated -> {output_path}")
    return str(output_path.resolve())


