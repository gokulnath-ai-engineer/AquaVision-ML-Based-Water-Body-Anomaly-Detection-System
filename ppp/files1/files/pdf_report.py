def _add_executive_summary(
    pdf: AquaSentinelPDF,
    detections: list,
    forensic_analyses: list,
    roi_info: dict,
) -> None:
    """Render the executive summary page."""
    pdf.add_page()
    _add_header(pdf, "EXECUTIVE SUMMARY")
    pdf.ln(2)

    sev_counts = _count_severities(detections, forensic_analyses)
    total = len(detections)
    assessment = _overall_assessment(sev_counts)
    hotspot = _find_critical_hotspot(detections, forensic_analyses)

    # Total anomalies
    pdf.set_font("Helvetica", "B", 11)
    pdf.cell(55, 8, "Total Anomalies Detected:")
    pdf.set_font("Helvetica", "B", 14)
    pdf.set_text_color(*COLOR_CRITICAL if sev_counts.get("CRITICAL", 0) > 0 else COLOR_BODY_TEXT)
    pdf.cell(0, 8, str(total), new_x="LMARGIN", new_y="NEXT")
    pdf.set_text_color(*COLOR_BODY_TEXT)
    pdf.ln(2)

    # Severity breakdown
    pdf.set_font("Helvetica", "B", 11)
    pdf.cell(0, 8, "Severity Breakdown:", new_x="LMARGIN", new_y="NEXT")
    pdf.ln(1)

    for sev in SEVERITY_ORDER:
        count = sev_counts.get(sev, 0)
        pdf.set_font("Helvetica", "", 10)
        pdf.cell(10, 7, "")
        _add_severity_badge(pdf, sev)
        pdf.set_font("Helvetica", "", 10)
        pdf.cell(5, 6, "")
        pdf.cell(0, 6, f"{count} detection(s)", new_x="LMARGIN", new_y="NEXT")

    pdf.ln(4)

    # Most critical hotspot
    pdf.set_font("Helvetica", "B", 11)
    pdf.cell(0, 8, "Most Critical Hotspot:", new_x="LMARGIN", new_y="NEXT")
    pdf.set_font("Helvetica", "", 10)
    lat = hotspot.get("centre_lat")
    lon = hotspot.get("centre_lon")
    if lat is not None and lon is not None:
        pdf.cell(10, 7, "")
        pdf.cell(0, 7, f"GPS Coordinates: {lat:.6f} N, {lon:.6f} E",
                 new_x="LMARGIN", new_y="NEXT")
        pdf.cell(10, 7, "")
        pdf.cell(0, 7, f"Chip: {hotspot.get('chip', 'N/A')}  |  "
                 f"Confidence: {hotspot.get('confidence', 0):.1%}",
                 new_x="LMARGIN", new_y="NEXT")
    else:
        pdf.cell(10, 7, "")
        pdf.cell(0, 7, "No GPS-referenced detections available.",
                 new_x="LMARGIN", new_y="NEXT")
    pdf.ln(4)

    # Overall assessment
    pdf.set_font("Helvetica", "B", 11)
    pdf.cell(0, 8, "Overall Water Quality Assessment:", new_x="LMARGIN", new_y="NEXT")
    pdf.set_font("Helvetica", "", 10)
    pdf.cell(10, 7, "")
    pdf.multi_cell(0, 7, assessment, new_x="LMARGIN", new_y="NEXT")
    pdf.ln(4)

    # Region summary
    pdf.set_font("Helvetica", "B", 11)
    pdf.cell(0, 8, "Monitored Region:", new_x="LMARGIN", new_y="NEXT")
    pdf.set_font("Helvetica", "", 10)
    water_body = roi_info.get("water_body", roi_info.get("name", "Unknown"))
    city = roi_info.get("city", "Unknown")
    state = roi_info.get("state", "Unknown")
    pdf.cell(10, 7, "")
    pdf.cell(0, 7, f"{water_body}, {city}, {state}", new_x="LMARGIN", new_y="NEXT")


