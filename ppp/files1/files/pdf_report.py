# Severity breakdown helpers
# ─────────────────────────────────────────────────

def _count_severities(detections: list, forensic_analyses: list) -> dict:
    """Count detections by severity. Uses forensic analysis when available."""
    counts = {s: 0 for s in SEVERITY_ORDER}

    # Build a lookup from forensic analyses
    forensic_severity_map = {}
    for fa in forensic_analyses:
        chip = fa.get("chip", fa.get("detection_id", ""))
        sev = fa.get("severity", "MONITOR").upper()
        forensic_severity_map[chip] = sev

    for det in detections:
        chip = det.get("chip", "")
        sev = forensic_severity_map.get(chip, "MONITOR").upper()
        if sev in counts:
            counts[sev] += 1
        else:
            counts["MONITOR"] += 1

    return counts


def _overall_assessment(severity_counts: dict) -> str:
    """Return a human-readable overall water quality assessment."""
    if severity_counts.get("CRITICAL", 0) > 0:
        return "CRITICAL -- Immediate intervention required. Multiple severe anomalies detected."
    if severity_counts.get("HIGH", 0) > 0:
        return "POOR -- Significant anomalies detected. Investigation and corrective action recommended."
    if severity_counts.get("WARNING", 0) > 0:
        return "FAIR -- Moderate anomalies observed. Continued monitoring and preventive measures advised."
    if severity_counts.get("MONITOR", 0) > 0:
        return "ACCEPTABLE -- Minor anomalies detected. Routine monitoring sufficient."
    return "GOOD -- No anomalies detected. Water quality within acceptable parameters."


def _find_critical_hotspot(detections: list, forensic_analyses: list) -> dict:
    """Find the GPS location of the most critical detection."""
    forensic_map = {}
    for fa in forensic_analyses:
        chip = fa.get("chip", fa.get("detection_id", ""))
        forensic_map[chip] = fa

    best = None
    best_rank = 99
    for det in detections:
        chip = det.get("chip", "")
        fa = forensic_map.get(chip, {})
        sev = fa.get("severity", "MONITOR")
        rank = _severity_rank(sev)
        conf = det.get("confidence", 0)
        if rank < best_rank or (rank == best_rank and best and conf > best.get("confidence", 0)):
            best_rank = rank
            best = det
    return best or {}


