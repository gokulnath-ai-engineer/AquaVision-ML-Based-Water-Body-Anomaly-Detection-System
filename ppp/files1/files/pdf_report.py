# ─────────────────────────────────────────────────
# Theme colours (R, G, B)
# ─────────────────────────────────────────────────
COLOR_HEADER_BG   = (15, 25, 55)
COLOR_HEADER_FG   = (255, 255, 255)
COLOR_CRITICAL    = (200, 50, 50)
COLOR_HIGH        = (230, 150, 30)
COLOR_WARNING     = (220, 200, 50)
COLOR_MONITOR     = (60, 160, 220)
COLOR_BODY_TEXT   = (30, 30, 30)
COLOR_MUTED       = (120, 120, 120)
COLOR_TABLE_HEADER = (20, 40, 80)
COLOR_TABLE_ROW_A = (240, 245, 255)
COLOR_TABLE_ROW_B = (255, 255, 255)
COLOR_ACCENT_LINE = (60, 160, 220)
COLOR_COVER_BG    = (10, 18, 42)
COLOR_COVER_ACCENT = (40, 180, 220)

SEVERITY_COLORS = {
    "CRITICAL": COLOR_CRITICAL,
    "HIGH":     COLOR_HIGH,
    "WARNING":  COLOR_WARNING,
    "MONITOR":  COLOR_MONITOR,
}

SEVERITY_ORDER = ["CRITICAL", "HIGH", "WARNING", "MONITOR"]

TIMESTAMP_FMT = "%Y-%m-%d %H:%M:%S UTC"


# ─────────────────────────────────────────────────
# Custom PDF class with automatic footer
# ─────────────────────────────────────────────────

class AquaSentinelPDF(FPDF):
    """FPDF subclass that adds a consistent footer to every page."""

    def __init__(self, *args, **kwargs):
        super().__init__(*args, **kwargs)
        self.generation_timestamp = datetime.utcnow().strftime(TIMESTAMP_FMT)
        self._skip_footer = False

    def footer(self):
        if self._skip_footer:
            return
        self.set_y(-15)
        self.set_font("Helvetica", "I", 7)
        self.set_text_color(*COLOR_MUTED)
        self.cell(0, 4, f"Generated by Aqua-Sentinel AI  |  {self.generation_timestamp}", align="L")
        self.cell(0, 4, f"Page {self.page_no()}/{{nb}}", align="R", new_x="LMARGIN", new_y="NEXT")


# ─────────────────────────────────────────────────
# Helper functions
# ─────────────────────────────────────────────────

def _add_header(pdf: FPDF, title: str) -> None:
    """Add a styled section header with a coloured background bar."""
    pdf.set_font("Helvetica", "B", 14)
    pdf.set_fill_color(*COLOR_HEADER_BG)
    pdf.set_text_color(*COLOR_HEADER_FG)
    pdf.cell(0, 10, f"  {title}", fill=True, new_x="LMARGIN", new_y="NEXT")
    # Accent underline
    pdf.set_draw_color(*COLOR_ACCENT_LINE)
    pdf.set_line_width(0.6)
    y = pdf.get_y()
    pdf.line(pdf.l_margin, y, pdf.w - pdf.r_margin, y)
    pdf.ln(4)
    # Reset text colour
    pdf.set_text_color(*COLOR_BODY_TEXT)


def _add_severity_badge(pdf: FPDF, severity: str) -> None:
    """Render a small coloured severity indicator inline."""
    severity_upper = severity.upper()
    color = SEVERITY_COLORS.get(severity_upper, COLOR_MUTED)
    pdf.set_fill_color(*color)
    pdf.set_text_color(255, 255, 255)
    pdf.set_font("Helvetica", "B", 9)
    badge_width = pdf.get_string_width(f" {severity_upper} ") + 4
    pdf.cell(badge_width, 6, f" {severity_upper} ", fill=True)
    pdf.set_text_color(*COLOR_BODY_TEXT)


def _add_table_row(pdf: FPDF, data: list, widths: list, colors: list = None) -> None:
    """
    Render a single table row with optional per-cell background colours.

    Parameters
    ----------
    pdf    : FPDF instance
    data   : list of cell text values
    widths : list of column widths (mm)
    colors : optional list of (R, G, B) tuples or None per cell
    """
    row_height = 7
    x_start = pdf.get_x()
    y_start = pdf.get_y()

    for i, (text, w) in enumerate(zip(data, widths)):
        if colors and colors[i] is not None:
            pdf.set_fill_color(*colors[i])
            fill = True
        else:
            fill = False
        pdf.set_xy(x_start + sum(widths[:i]), y_start)
        pdf.cell(w, row_height, str(text), border=1, fill=fill)

    pdf.set_xy(x_start, y_start + row_height)


def _severity_rank(severity: str) -> int:
    """Return a numeric rank for severity (lower = more severe)."""
    try:
        return SEVERITY_ORDER.index(severity.upper())
    except ValueError:
        return 99


def _safe_text(text) -> str:
    """Ensure text is a string suitable for PDF rendering."""
    if text is None:
        return "N/A"
    return str(text)


def _check_page_space(pdf: FPDF, needed_mm: float) -> None:
    """Add a new page if remaining space is less than needed_mm."""
    if pdf.get_y() + needed_mm > pdf.h - 20:
        pdf.add_page()


