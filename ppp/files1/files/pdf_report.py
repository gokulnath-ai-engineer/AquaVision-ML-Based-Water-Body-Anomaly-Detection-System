def _add_recommendations(
    pdf: AquaSentinelPDF,
    detections: list,
    forensic_analyses: list,
) -> None:
    """Render prioritised recommendations and follow-up timeline."""
    pdf.add_page()
    _add_header(pdf, "RECOMMENDATIONS")
    pdf.ln(2)

    sev_counts = _count_severities(detections, forensic_analyses)

    # Collect unique recommended actions from forensic analyses
    actions_by_severity = {s: [] for s in SEVERITY_ORDER}
    for fa in forensic_analyses:
        sev = fa.get("severity", "MONITOR").upper()
        action = fa.get("recommended_action", fa.get("action", None))
        if action and sev in actions_by_severity:
            if action not in actions_by_severity[sev]:
                actions_by_severity[sev].append(action)

    # Prioritised action list
    pdf.set_font("Helvetica", "B", 11)
    pdf.cell(0, 8, "Prioritised Action Items:", new_x="LMARGIN", new_y="NEXT")
    pdf.ln(2)

    action_num = 0
    for sev in SEVERITY_ORDER:
        for action in actions_by_severity[sev]:
            action_num += 1
            _check_page_space(pdf, 14)
            pdf.set_font("Helvetica", "B", 10)
            pdf.cell(8, 7, "")
            _add_severity_badge(pdf, sev)
            pdf.set_font("Helvetica", "", 9)
            pdf.cell(5, 6, "")
            pdf.multi_cell(0, 6, f"{action_num}. {_safe_text(action)}",
                           new_x="LMARGIN", new_y="NEXT")
            pdf.ln(1)

    if action_num == 0:
        # Generate default recommendations based on severity counts
        default_actions = []
        if sev_counts.get("CRITICAL", 0) > 0:
            default_actions.append(
                ("CRITICAL", "Dispatch emergency response team to identified hotspot(s). "
                 "Initiate water sampling within 24 hours.")
            )
            default_actions.append(
                ("CRITICAL", "Notify relevant environmental regulatory authorities immediately.")
            )
        if sev_counts.get("HIGH", 0) > 0:
            default_actions.append(
                ("HIGH", "Conduct on-site investigation at flagged locations within 48 hours.")
            )
            default_actions.append(
                ("HIGH", "Review upstream industrial discharge permits and compliance records.")
            )
        if sev_counts.get("WARNING", 0) > 0:
            default_actions.append(
                ("WARNING", "Increase monitoring frequency for affected zones to daily intervals.")
            )
            default_actions.append(
                ("WARNING", "Cross-reference with recent weather events and agricultural runoff patterns.")
            )
        if sev_counts.get("MONITOR", 0) > 0:
            default_actions.append(
                ("MONITOR", "Continue routine satellite surveillance at standard intervals.")
            )

        if not default_actions:
            default_actions.append(
                ("MONITOR", "No anomalies detected. Maintain current monitoring schedule.")
            )

        for i, (sev, action) in enumerate(default_actions, 1):
            _check_page_space(pdf, 14)
            pdf.set_font("Helvetica", "B", 10)
            pdf.cell(8, 7, "")
            _add_severity_badge(pdf, sev)
            pdf.set_font("Helvetica", "", 9)
            pdf.cell(5, 6, "")
            pdf.multi_cell(0, 6, f"{i}. {action}", new_x="LMARGIN", new_y="NEXT")
            pdf.ln(1)

    # Follow-up timeline
    pdf.ln(6)
    _check_page_space(pdf, 50)
    _add_header(pdf, "SUGGESTED FOLLOW-UP TIMELINE")
    pdf.ln(2)

    has_critical = sev_counts.get("CRITICAL", 0) > 0
    has_high = sev_counts.get("HIGH", 0) > 0
    has_warning = sev_counts.get("WARNING", 0) > 0

    timeline = []
    if has_critical:
        timeline.append(("0 - 24 hours", "CRITICAL",
                         "Emergency field verification and water sampling at critical hotspots."))
        timeline.append(("24 - 48 hours", "CRITICAL",
                         "Laboratory analysis of collected samples. "
                         "Notify regulatory bodies with preliminary findings."))
    if has_high:
        timeline.append(("48 - 72 hours", "HIGH",
                         "On-site investigation of high-severity zones. "
                         "Identify potential discharge sources."))
    if has_critical or has_high:
        timeline.append(("1 week", "HIGH",
                         "Follow-up satellite acquisition for change detection analysis."))
    if has_warning:
        timeline.append(("1 - 2 weeks", "WARNING",
                         "Expanded monitoring of warning-level areas. "
                         "Review historical trends."))
    timeline.append(("30 days", "MONITOR",
                     "Comprehensive re-assessment with updated satellite imagery. "
                     "Generate comparative report."))
    timeline.append(("Quarterly", "MONITOR",
                     "Routine satellite surveillance cycle and compliance review."))

    col_widths_tl = [35, 25, 130]
    headers_tl = ["Timeframe", "Priority", "Action"]
    pdf.set_font("Helvetica", "B", 8)
    pdf.set_fill_color(*COLOR_TABLE_HEADER)
    pdf.set_text_color(255, 255, 255)
    _add_table_row(pdf, headers_tl, col_widths_tl,
                   [COLOR_TABLE_HEADER] * len(headers_tl))
    pdf.set_text_color(*COLOR_BODY_TEXT)

    pdf.set_font("Helvetica", "", 8)
    for idx, (timeframe, priority, action) in enumerate(timeline):
        _check_page_space(pdf, 10)
        sev_color = SEVERITY_COLORS.get(priority, COLOR_MUTED)
        sev_bg = tuple(min(255, int(c * 0.3 + 255 * 0.7)) for c in sev_color)
        row_bg = COLOR_TABLE_ROW_A if idx % 2 == 0 else COLOR_TABLE_ROW_B
        row_colors = [row_bg, sev_bg, row_bg]
        _add_table_row(pdf, [timeframe, priority, action[:75]], col_widths_tl, row_colors)


