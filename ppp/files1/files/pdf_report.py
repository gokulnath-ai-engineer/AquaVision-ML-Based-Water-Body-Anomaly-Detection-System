def _add_detection_log_table(
    pdf: AquaSentinelPDF,
    detections: list,
    forensic_analyses: list,
) -> None:
    """Render the detection log as a colour-coded table."""
    pdf.add_page()
    _add_header(pdf, "DETECTION LOG")
    pdf.ln(2)

    if not detections:
        pdf.set_font("Helvetica", "I", 10)
        pdf.cell(0, 8, "No detections recorded.", new_x="LMARGIN", new_y="NEXT")
        return

    # Build forensic severity map
    forensic_map = {}
    for fa in forensic_analyses:
        chip = fa.get("chip", fa.get("detection_id", ""))
        forensic_map[chip] = fa

    # Column definitions:  #, Location, Type, Confidence, Severity, GPS
    col_widths = [10, 40, 35, 25, 25, 55]
    headers = ["#", "Location", "Type", "Conf.", "Severity", "GPS"]

    # Table header
    pdf.set_font("Helvetica", "B", 8)
    pdf.set_fill_color(*COLOR_TABLE_HEADER)
    pdf.set_text_color(255, 255, 255)
    header_colors = [COLOR_TABLE_HEADER] * len(headers)
    _add_table_row(pdf, headers, col_widths, header_colors)
    pdf.set_text_color(*COLOR_BODY_TEXT)

    # Table rows
    pdf.set_font("Helvetica", "", 7)
    for idx, det in enumerate(detections):
        _check_page_space(pdf, 10)

        # Re-render header on new page
        if pdf.get_y() <= pdf.t_margin + 2:
            pdf.set_font("Helvetica", "B", 8)
            pdf.set_text_color(255, 255, 255)
            _add_table_row(pdf, headers, col_widths, header_colors)
            pdf.set_text_color(*COLOR_BODY_TEXT)
            pdf.set_font("Helvetica", "", 7)

        chip = det.get("chip", "N/A")
        det_class = det.get("class", "N/A")
        conf = det.get("confidence", 0)
        lat = det.get("centre_lat")
        lon = det.get("centre_lon")

        fa = forensic_map.get(chip, {})
        severity = fa.get("severity", "MONITOR").upper()

        gps_str = f"{lat:.4f}, {lon:.4f}" if lat is not None and lon is not None else "N/A"

        # Severity colour for the severity cell
        sev_color = SEVERITY_COLORS.get(severity, COLOR_MUTED)
        # Lighter version for cell background
        sev_bg = tuple(min(255, int(c * 0.3 + 255 * 0.7)) for c in sev_color)

        # Alternating row background
        row_bg = COLOR_TABLE_ROW_A if idx % 2 == 0 else COLOR_TABLE_ROW_B
        row_colors = [row_bg, row_bg, row_bg, row_bg, sev_bg, row_bg]

        row_data = [
            str(idx + 1),
            chip[:20] if len(chip) > 20 else chip,
            det_class,
            f"{conf:.1%}",
            severity,
            gps_str,
        ]

        _add_table_row(pdf, row_data, col_widths, row_colors)

    pdf.ln(4)
    pdf.set_font("Helvetica", "I", 8)
    pdf.set_text_color(*COLOR_MUTED)
    pdf.cell(0, 6, f"Total detections: {len(detections)}", new_x="LMARGIN", new_y="NEXT")
    pdf.set_text_color(*COLOR_BODY_TEXT)


# ─────────────────────────────────────────────────
# Spectral analysis summary
# ─────────────────────────────────────────────────

def _add_spectral_analysis(
    pdf: AquaSentinelPDF,
    detections: list,
    forensic_analyses: list,
) -> None:
    """Render the spectral analysis summary section."""
    pdf.add_page()
    _add_header(pdf, "SPECTRAL ANALYSIS SUMMARY")
    pdf.ln(2)

    # Collect spectral data from forensic analyses
    ndwi_values = []
    chlorophyll_values = []
    turbidity_values = []
    water_quality_scores = []

    for fa in forensic_analyses:
        spectral = fa.get("spectral", fa.get("spectral_data", {}))
        if isinstance(spectral, dict):
            if "ndwi" in spectral:
                ndwi_values.append(spectral["ndwi"])
            if "chlorophyll" in spectral or "chlorophyll_a" in spectral:
                chlorophyll_values.append(
                    spectral.get("chlorophyll", spectral.get("chlorophyll_a", 0))
                )
            if "turbidity" in spectral:
                turbidity_values.append(spectral["turbidity"])
            if "water_quality_score" in spectral:
                water_quality_scores.append(spectral["water_quality_score"])

    # NDWI statistics
    pdf.set_font("Helvetica", "B", 11)
    pdf.cell(0, 8, "NDWI (Normalized Difference Water Index)", new_x="LMARGIN", new_y="NEXT")
    pdf.set_font("Helvetica", "", 10)
    if ndwi_values:
        pdf.cell(10, 7, "")
        pdf.cell(0, 7, f"Mean:  {sum(ndwi_values) / len(ndwi_values):.4f}",
                 new_x="LMARGIN", new_y="NEXT")
        pdf.cell(10, 7, "")
        pdf.cell(0, 7, f"Min:   {min(ndwi_values):.4f}    Max: {max(ndwi_values):.4f}",
                 new_x="LMARGIN", new_y="NEXT")
        pdf.cell(10, 7, "")
        pdf.cell(0, 7, f"Samples: {len(ndwi_values)}", new_x="LMARGIN", new_y="NEXT")
    else:
        pdf.cell(10, 7, "")
        pdf.cell(0, 7, "No NDWI data available from current analysis.",
                 new_x="LMARGIN", new_y="NEXT")
    pdf.ln(4)

    # Chlorophyll-a levels
    pdf.set_font("Helvetica", "B", 11)
    pdf.cell(0, 8, "Chlorophyll-a Levels", new_x="LMARGIN", new_y="NEXT")
    pdf.set_font("Helvetica", "", 10)
    if chlorophyll_values:
        mean_chl = sum(chlorophyll_values) / len(chlorophyll_values)
        pdf.cell(10, 7, "")
        pdf.cell(0, 7, f"Mean:  {mean_chl:.4f}", new_x="LMARGIN", new_y="NEXT")
