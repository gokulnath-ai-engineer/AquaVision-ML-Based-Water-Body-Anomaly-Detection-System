def _add_cover_page(pdf: AquaSentinelPDF, roi_info: dict) -> None:
    """Render the cover page of the incident report."""
    pdf._skip_footer = True
    pdf.add_page()

    # Dark background fill
    pdf.set_fill_color(*COLOR_COVER_BG)
    pdf.rect(0, 0, pdf.w, pdf.h, "F")

    # Top accent bar
    pdf.set_fill_color(*COLOR_COVER_ACCENT)
    pdf.rect(0, 0, pdf.w, 4, "F")

    # Classification banner at top
    pdf.set_y(15)
    pdf.set_font("Courier", "B", 9)
    pdf.set_text_color(200, 60, 60)
    pdf.cell(0, 6, "CONFIDENTIAL -- FOR AUTHORIZED PERSONNEL ONLY", align="C",
             new_x="LMARGIN", new_y="NEXT")
    pdf.ln(25)

    # Title
    pdf.set_font("Helvetica", "B", 28)
    pdf.set_text_color(*COLOR_COVER_ACCENT)
    pdf.cell(0, 14, "AQUA-SENTINEL AI", align="C", new_x="LMARGIN", new_y="NEXT")
    pdf.ln(2)

    # Divider
    pdf.set_draw_color(*COLOR_COVER_ACCENT)
    pdf.set_line_width(0.8)
    mid_x = pdf.w / 2
    pdf.line(mid_x - 60, pdf.get_y(), mid_x + 60, pdf.get_y())
    pdf.ln(6)

    pdf.set_font("Helvetica", "B", 18)
    pdf.set_text_color(255, 255, 255)
    pdf.cell(0, 12, "INCIDENT REPORT", align="C", new_x="LMARGIN", new_y="NEXT")
    pdf.ln(4)

    pdf.set_font("Helvetica", "", 13)
    pdf.set_text_color(180, 200, 220)
    pdf.cell(0, 8, "Water Quality Anomaly Assessment", align="C",
             new_x="LMARGIN", new_y="NEXT")
    pdf.ln(20)

    # Water body information block
    pdf.set_font("Helvetica", "", 11)
    pdf.set_text_color(160, 180, 200)

    water_body = roi_info.get("water_body", roi_info.get("name", "Unknown"))
    state = roi_info.get("state", "Unknown")
    city = roi_info.get("city", "Unknown")
    now = datetime.utcnow()

    info_lines = [
        ("Water Body", water_body),
        ("Location", f"{city}, {state}"),
        ("Report Date", now.strftime("%B %d, %Y")),
        ("Report Time", now.strftime("%H:%M:%S UTC")),
        ("Water Type", roi_info.get("water_type", "N/A").capitalize()),
        ("Bounding Box",
         f"{roi_info.get('lat_min', 'N/A')}N, {roi_info.get('lon_min', 'N/A')}E  to  "
         f"{roi_info.get('lat_max', 'N/A')}N, {roi_info.get('lon_max', 'N/A')}E"),
    ]

    for label, value in info_lines:
        pdf.set_font("Helvetica", "B", 10)
        pdf.set_text_color(100, 140, 180)
        pdf.cell(55, 8, f"{label}:", align="R")
        pdf.set_font("Helvetica", "", 11)
        pdf.set_text_color(220, 230, 240)
        pdf.cell(0, 8, f"  {value}", new_x="LMARGIN", new_y="NEXT")

    # Bottom accent bar
    pdf.set_fill_color(*COLOR_COVER_ACCENT)
    pdf.rect(0, pdf.h - 4, pdf.w, 4, "F")

    # System identifier at bottom
    pdf.set_y(pdf.h - 20)
    pdf.set_font("Courier", "", 7)
    pdf.set_text_color(80, 100, 120)
    pdf.cell(0, 4, f"Report ID: AQSI-{now.strftime('%Y%m%d%H%M%S')}  |  "
             f"System: {DASHBOARD.get('title', 'Aqua-Sentinel AI')}  |  "
             f"{DASHBOARD.get('subtitle', '')}",
             align="C", new_x="LMARGIN", new_y="NEXT")

    pdf._skip_footer = False


