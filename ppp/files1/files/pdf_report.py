def generate_incident_report(
    detections: list,
    forensic_analyses: list,
    roi_info: dict = None,
    output_path: str = None,
    detection_images: list = None,
) -> str:
    """
    Generate a complete PDF incident report.

    Parameters
    ----------
    detections : list[dict]
        List of detection records. Each dict should contain keys such as
        'chip', 'confidence', 'class', 'centre_lat', 'centre_lon', 'bbox_px',
        'timestamp'.
    forensic_analyses : list[dict]
        List of forensic analysis records. Each dict may contain keys such as
        'chip'/'detection_id', 'verdict', 'severity', 'confidence',
        'reasoning'/'reasoning_chain', 'recommended_action', 'spectral'.
    roi_info : dict, optional
        Region of interest information. Defaults to config.ROI.
    output_path : str, optional
        Path for the output PDF. Defaults to INFER["report_pdf"].
    detection_images : list[str], optional
        List of paths to detection images (currently reserved for future use).

    Returns
    -------
    str
        The absolute path to the generated PDF report.
    """
    if roi_info is None:
        roi_info = ROI
    if output_path is None:
        output_path = INFER["report_pdf"]

    output_path = Path(output_path)
    output_path.parent.mkdir(parents=True, exist_ok=True)

    if detections is None:
        detections = []
    if forensic_analyses is None:
        forensic_analyses = []

    pdf = AquaSentinelPDF(orientation="P", unit="mm", format="A4")
    pdf.alias_nb_pages()
    pdf.set_auto_page_break(auto=True, margin=20)

    # 1. Cover page
    _add_cover_page(pdf, roi_info)

    # 2. Executive summary
    _add_executive_summary(pdf, detections, forensic_analyses, roi_info)

    # 3. Forensic analysis
    _add_forensic_analysis_section(pdf, forensic_analyses)

    # 4. Detection log table
    _add_detection_log_table(pdf, detections, forensic_analyses)

    # 5. Spectral analysis summary
    _add_spectral_analysis(pdf, detections, forensic_analyses)

    # 6. Recommendations
    _add_recommendations(pdf, detections, forensic_analyses)

    # Write PDF
    pdf.output(str(output_path))

    print(f"[PDF] Incident report generated -> {output_path}")
    return str(output_path.resolve())


