# ─────────────────────────────────────────────────

def _add_forensic_analysis_section(
    pdf: AquaSentinelPDF,
    forensic_analyses: list,
) -> None:
    """Render the forensic analysis section with per-detection verdicts."""
    pdf.add_page()
    _add_header(pdf, "FORENSIC ANALYSIS")
    pdf.ln(2)

    if not forensic_analyses:
        pdf.set_font("Helvetica", "I", 10)
        pdf.cell(0, 8, "No forensic analyses available for this report.",
                 new_x="LMARGIN", new_y="NEXT")
        return

    for idx, fa in enumerate(forensic_analyses):
        _check_page_space(pdf, 60)

        # Analysis header
        pdf.set_font("Helvetica", "B", 11)
        pdf.set_fill_color(230, 235, 245)
        chip = fa.get("chip", fa.get("detection_id", f"Analysis-{idx + 1}"))
        pdf.cell(0, 8, f"  Analysis #{idx + 1}  --  {chip}", fill=True,
                 new_x="LMARGIN", new_y="NEXT")
        pdf.ln(2)

        # Verdict
        pdf.set_font("Helvetica", "B", 10)
        pdf.cell(30, 7, "Verdict:")
        pdf.set_font("Helvetica", "", 10)
        verdict = fa.get("verdict", "No verdict available")
        pdf.multi_cell(0, 7, _safe_text(verdict), new_x="LMARGIN", new_y="NEXT")

        # Severity badge
        pdf.set_font("Helvetica", "B", 10)
        pdf.cell(30, 7, "Severity:")
        severity = fa.get("severity", "MONITOR")
        _add_severity_badge(pdf, severity)
        pdf.ln(8)

        # Confidence
        pdf.set_font("Helvetica", "B", 10)
        pdf.cell(30, 7, "Confidence:")
        pdf.set_font("Helvetica", "", 10)
        confidence = fa.get("confidence", fa.get("confidence_score", None))
        if confidence is not None:
            if isinstance(confidence, (int, float)) and confidence <= 1.0:
                pdf.cell(0, 7, f"{confidence:.1%}", new_x="LMARGIN", new_y="NEXT")
            else:
                pdf.cell(0, 7, f"{confidence}", new_x="LMARGIN", new_y="NEXT")
        else:
            pdf.cell(0, 7, "N/A", new_x="LMARGIN", new_y="NEXT")

        # Reasoning chain
        reasoning = fa.get("reasoning", fa.get("reasoning_chain", []))
        if reasoning:
            pdf.set_font("Helvetica", "B", 10)
            pdf.cell(0, 7, "Reasoning Chain:", new_x="LMARGIN", new_y="NEXT")
            pdf.set_font("Helvetica", "", 9)
            if isinstance(reasoning, list):
                for step_num, step in enumerate(reasoning, 1):
                    _check_page_space(pdf, 10)
                    pdf.cell(10, 6, "")
                    pdf.multi_cell(0, 6, f"{step_num}. {_safe_text(step)}",
                                   new_x="LMARGIN", new_y="NEXT")
            else:
                pdf.cell(10, 6, "")
                pdf.multi_cell(0, 6, _safe_text(reasoning),
                               new_x="LMARGIN", new_y="NEXT")

        # Recommended action
        action = fa.get("recommended_action", fa.get("action", None))
        if action:
            _check_page_space(pdf, 12)
            pdf.set_font("Helvetica", "B", 10)
            pdf.cell(0, 7, "Recommended Action:", new_x="LMARGIN", new_y="NEXT")
            pdf.set_font("Helvetica", "", 9)
            pdf.cell(10, 6, "")
            pdf.multi_cell(0, 6, _safe_text(action), new_x="LMARGIN", new_y="NEXT")

        pdf.ln(4)

        # Separator between analyses
        if idx < len(forensic_analyses) - 1:
            pdf.set_draw_color(*COLOR_MUTED)
            pdf.set_line_width(0.2)
            y = pdf.get_y()
            pdf.line(pdf.l_margin + 10, y, pdf.w - pdf.r_margin - 10, y)
            pdf.ln(4)


